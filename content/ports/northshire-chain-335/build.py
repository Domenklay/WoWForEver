#!/usr/bin/env python3
"""Generate reviewed SQL from the pinned TDB donor snapshot; no network or DB access."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent
SOURCE = json.loads((ROOT / 'source.json').read_text())
QUESTS = {q['ID']: q for q in SOURCE['quest_template']}
NPCS = {n['entry']: n for n in SOURCE['creature_template']}
QIDS = sorted(910000 + q for q in QUESTS)
NIDS = sorted(910000 + n for n in NPCS)
GUIDS = {n: 910000001 + i for i, n in enumerate(sorted(NPCS))}
NAME = 'northshire-chain-335-v1'

def literal(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + v.replace('\\', '\\\\').replace("'", "''") + "'"

def ids(values):
    return ','.join(str(v) for v in sorted(values))

def insert(table, row):
    return '  INSERT INTO `' + table + '` (' + ','.join('`'+k+'`' for k in row) + ') VALUES (' + ','.join(literal(v) for v in row.values()) + ');\n'

def clone(table, key, source, target, changes=None):
    changes = {key: target, **(changes or {})}
    return f'''  CREATE TEMPORARY TABLE wf_chain_copy LIKE `{table}`;
  INSERT INTO wf_chain_copy SELECT * FROM `{table}` WHERE `{key}`={source};
  UPDATE wf_chain_copy SET {','.join('`'+k+'`='+literal(v) for k,v in changes.items())};
  INSERT INTO `{table}` SELECT * FROM wf_chain_copy;
  DROP TEMPORARY TABLE wf_chain_copy;
'''

def link(value):
    # Do not accidentally unlock or depend on the original Forever quests.
    return (1 if value >= 0 else -1) * (910000 + abs(value)) if abs(value) in QUESTS else 0

preamble = '''-- GPL-2.0; derived from TrinityCore TDB335.26091. See source.json and README.md.
-- Generated by build.py. Apply only with game services stopped.
CREATE TABLE IF NOT EXISTS wowforever_content_ports (
  name varchar(80) NOT NULL PRIMARY KEY,
  installed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
'''

def begin(proc, installed):
    return preamble + f'''DROP PROCEDURE IF EXISTS {proc};
DELIMITER //
CREATE PROCEDURE {proc}()
main: BEGIN
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  IF {'EXISTS' if installed else 'NOT EXISTS'} (SELECT 1 FROM wowforever_content_ports WHERE name='{NAME}') THEN
    COMMIT;
    SELECT '{'Already installed' if installed else 'Not installed'}; no changes' AS result;
    LEAVE main;
  END IF;
'''

def end(proc, result):
    return f'''  COMMIT;
  SELECT '{result}' AS result;
END//
DELIMITER ;
CALL {proc}();
DROP PROCEDURE {proc};
'''

# All owned IDs, including relationship-only/orphan rows, must be free before installation.
owned = [('quest_template','ID',QIDS), ('quest_template_addon','ID',QIDS),
         ('quest_classic_level','ID',QIDS), ('quest_classic_money','ID',QIDS),
         ('quest_template_classic_level','ID',QIDS), ('quest_offer_reward','ID',QIDS),
         ('quest_request_items','ID',QIDS), ('quest_objectives','QuestID',QIDS),
         ('creature_template','entry',NIDS), ('creature_template_model','CreatureID',NIDS),
         ('creature_template_difficulty','Entry',NIDS), ('creature','guid',list(GUIDS.values())),
         ('creature','id',NIDS)]
for table in ('creature_queststarter','creature_questender'):
    owned += [(table,'id',NIDS),(table,'quest',QIDS)]
objectives = []
for q, row in sorted(QUESTS.items()):
    for i in range(1,5):
        target, amount = row[f'RequiredNpcOrGo{i}'], row[f'RequiredNpcOrGoCount{i}']
        if target and amount:
            assert target > 0, 'Gameobject objectives need a separate conversion'
            objectives.append(dict(ID=9100000+q*10+i-1,QuestID=910000+q,Type=0,
                                   Order=i-1,StorageIndex=i-1,ObjectID=target,Amount=amount,Description=row[f'ObjectiveText{i}']))
    for i in range(1,7):
        target, amount = row[f'RequiredItemId{i}'], row[f'RequiredItemCount{i}']
        if target and amount:
            objectives.append(dict(ID=9100000+q*10+3+i,QuestID=910000+q,Type=1,
                                   Order=3+i,StorageIndex=3+i,ObjectID=target,Amount=amount,Description=''))
# Make the hand-off explicit instead of depending on legacy no-objective/auto-accept behaviour.
objectives.append(dict(ID=9107830,QuestID=910783,Type=3,Order=0,StorageIndex=0,
                       ObjectID=910197,Amount=1,Description='Speak with [335 chain] Marshal McBride'))
owned += [('quest_objectives','ID',[o['ID'] for o in objectives])]

s = begin('wf_install_northshire_chain', True)
checks = []
for q in QUESTS:
    checks.append(f'NOT EXISTS (SELECT 1 FROM quest_template WHERE ID={q})')
for q, row in QUESTS.items():
    # Require the same item references as the working Forever counterpart.
    for field in ['StartItem'] + [f'RewardChoiceItemID{i}' for i in range(1,7)] + [f'RewardItem{i}' for i in range(1,5)]:
        if row[field]:
            checks.append(f'NOT EXISTS (SELECT 1 FROM quest_template WHERE ID={q} AND `{field}`={row[field]})')
for n in NPCS:
    checks += [f'NOT EXISTS (SELECT 1 FROM {t} WHERE {k}={n})' for t,k in
               [('creature_template','entry'),('creature_template_model','CreatureID'),('creature_template_difficulty','Entry')]]
    checks.append(f'NOT EXISTS (SELECT 1 FROM creature WHERE id={n} AND map=0)')
for n in {o['ObjectID'] for o in objectives if o['Type']==0}:
    checks += [f'NOT EXISTS (SELECT 1 FROM creature_template WHERE entry={n})',
               f'NOT EXISTS (SELECT 1 FROM creature WHERE id={n} AND map=0)']
s += '  IF ' + '\n     OR '.join(checks) + " THEN\n    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Missing Northshire prerequisites; no content installed';\n  END IF;\n"
s += '  IF ' + '\n     OR '.join(f'EXISTS (SELECT 1 FROM `{t}` WHERE `{k}` IN ({ids(v)}))' for t,k,v in owned) + " THEN\n    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Reserved chain IDs occupied; no content installed';\n  END IF;\n"

for q, row in sorted(QUESTS.items()):
    shared = ['QuestType','QuestSortID','QuestInfoID','SuggestedGroupNum','RewardXPDifficulty','RewardBonusMoney',
              'RewardSpell','RewardHonor','RewardKillHonor','StartItem','Flags','RewardFactionFlags','AllowableRaces',
              'TimeAllowed','LogTitle','LogDescription','QuestDescription','AreaDescription','QuestCompletionLog']
    for i in range(1,5):
        shared += [f'RewardItem{i}',f'RewardAmount{i}',f'ItemDrop{i}',f'ItemDropQuantity{i}']
    for i in range(1,7):
        shared += [f'RewardChoiceItemID{i}',f'RewardChoiceItemQuantity{i}']
    for i in range(1,6):
        shared += [f'RewardFactionID{i}',f'RewardFactionValue{i}',f'RewardFactionOverride{i}']
    changes = {k:row[k] for k in shared}
    changes['Flags'] &= ~0x80000  # Require a normal explicit accept on the Forever client.
    changes.update(LogTitle='[335 chain] '+row['LogTitle'], RewardNextQuest=link(row['RewardNextQuest']), VerifiedBuild=0)
    s += clone('quest_template','ID',q,910000+q,changes)
    addon = next(a.copy() for a in SOURCE['quest_template_addon'] if a['ID']==q)
    addon['ID'] = 910000+q
    addon['SpecialFlags'] &= ~4  # Do not inherit legacy auto-accept.
    for key in ('PrevQuestID','NextQuestID','BreadcrumbForQuestId'):
        addon[key]=link(addon[key])
    assert addon['ExclusiveGroup']==0
    s += insert('quest_template_addon',addon)
    s += insert('quest_classic_level',dict(ID=910000+q,QuestLevel=row['QuestLevel'],MinLevel=row['MinLevel'],MaxLevel=0))
    s += insert('quest_template_classic_level',dict(ID=910000+q,LevelType=2,QuestLevel=row['QuestLevel']))
    s += insert('quest_classic_money',dict(ID=910000+q,RewardMoney=row['RewardMoney'],RewardMoneyMaxLevel=row['RewardBonusMoney']))
for obj in objectives:
    s += insert('quest_objectives',obj)
for table in ('quest_offer_reward','quest_request_items'):
    for r in SOURCE[table]:
        row={**r,'ID':910000+r['ID'],'VerifiedBuild':0}
        s += insert(table,row)
for n,row in sorted(NPCS.items()):
    new=910000+n
    s += clone('creature_template','entry',n,new,dict(name='[335 chain] '+row['name'],npcflag=3,AIName='',ScriptName='',VerifiedBuild=0))
    s += clone('creature_template_model','CreatureID',n,new)
    s += clone('creature_template_difficulty','Entry',n,new)
    s += f'''  CREATE TEMPORARY TABLE wf_chain_copy LIKE creature;
  INSERT INTO wf_chain_copy SELECT * FROM creature WHERE id={n} AND map=0 ORDER BY guid LIMIT 1;
  UPDATE wf_chain_copy SET guid={GUIDS[n]},id={new},position_x=position_x+3,
    position_y=position_y-1.5,MovementType=0,wander_distance=0,ScriptName='',VerifiedBuild=0;
  INSERT INTO creature SELECT * FROM wf_chain_copy;
  DROP TEMPORARY TABLE wf_chain_copy;
'''
for table in ('creature_queststarter','creature_questender'):
    for row in SOURCE[table]:
        assert row['id'] in NPCS
        s += insert(table,dict(id=910000+row['id'],quest=910000+row['quest']))
s += insert('wowforever_content_ports',dict(name=NAME))
s += end('wf_install_northshire_chain','Installed Northshire chain: 5 quests, 3 NPCs; original and first-test quests unchanged')
(ROOT/'apply.sql').write_text(s)
r = begin('wf_remove_northshire_chain', False)
for table,key,values in owned:
    if (table,key) in [('creature','id'),('quest_objectives','ID')]:
        continue
    r += f'  DELETE FROM `{table}` WHERE `{key}` IN ({ids(values)});\n'
r += f"  DELETE FROM wowforever_content_ports WHERE name='{NAME}';\n"
r += end('wf_remove_northshire_chain','Removed Northshire chain; character progress and original quests retained')
(ROOT/'rollback.sql').write_text(r)
print(f'Generated 5 quests, {len(objectives)} objectives and 3 NPCs')

repair = begin('wf_repair_northshire_chain', False)
repair += """  IF (SELECT COUNT(*) FROM quest_template WHERE ID IN (910783,910007,910015,910021,910054)) <> 5
     OR (SELECT COUNT(*) FROM creature_template WHERE entry IN (910823,910197,910240)) <> 3 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Incomplete chain installation; repair stopped';
  END IF;
  IF EXISTS (SELECT 1 FROM quest_objectives WHERE ID=9107830 AND
     (QuestID<>910783 OR Type<>3 OR ObjectID<>910197 OR Amount<>1 OR StorageIndex<>0))
     OR EXISTS (SELECT 1 FROM quest_objectives WHERE QuestID=910783 AND ID<>9107830) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Unexpected objective data; repair stopped';
  END IF;
  UPDATE quest_template SET Flags=Flags & ~524288
    WHERE ID IN (910783,910007,910015,910021,910054);
  UPDATE quest_template_addon SET SpecialFlags=SpecialFlags & ~4
    WHERE ID IN (910783,910007,910015,910021,910054);
  UPDATE creature_template SET npcflag=npcflag | 3
    WHERE entry IN (910823,910197,910240);
  INSERT INTO quest_objectives (ID,QuestID,Type,`Order`,StorageIndex,ObjectID,Amount,Description)
    VALUES (9107830,910783,3,0,0,910197,1,'Speak with [335 chain] Marshal McBride')
    ON DUPLICATE KEY UPDATE Description=VALUES(Description);
  DELETE FROM creature_questender WHERE quest=910783;
  INSERT INTO creature_questender (id,quest) VALUES (910197,910783);
"""
repair += end('wf_repair_northshire_chain','Repaired hand-off to chain Marshal McBride; abandon and retake active introductory quest')
(ROOT/'repair.sql').write_text(repair)
