# texts the page script needs
JS_KEYS = ('status_online', 'status_offline', 'players_one', 'players_many', 'download_for', 'copy', 'copied')


def pick_language(query: str | None, cookie: str | None, accept: str | None) -> str:
    for code in (query, cookie):
        if code in TEXTS:
            return code
    # Accept-Language: "es-AR,es;q=0.9,en;q=0.8" (order is good enough, q values are nearly always decreasing)
    for part in (accept or '').split(','):
        code = part.split(';')[0].strip()[:2].lower()
        if code in TEXTS:
            return code
    return DEFAULT


def translator(lang: str):
    texts = TEXTS[lang]

    def t(key: str, **values) -> Markup:
        return Markup(texts.get(key) or TEXTS[DEFAULT][key]).format(**values)

    return t


def js_texts(lang: str) -> dict:
    return {k: TEXTS[lang][k] for k in JS_KEYS}
